function normalizeForLookup(s: string): string {
  return s
    .trim()
    .toLowerCase()
    .replace(/[إأآا]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/\s+/g, " ")
    .trim();
}

// explicit hints from the user's Round 36 feedback message that should win
// over the uploaded reference file's first-listed unit for these specific
// cases (checked in order — first match wins).
const OVERRIDE_RULES: { test: (n: string) => boolean; unit: string }[] = [
  {
    test: (n) =>
      /بيبسي|كولا|سفن اب|سفن أب|مياه|صودا|مشروبات غاز|مشروب غاز|عصير غاز/.test(n),
    unit: "زجاجة",
  },
  // "لبن لتر علي طول" — لبن من غير أي وصف زيادة (رايب/بودرة/...) بتتحط
  // "لتر" افتراضيًا. صياغات فيها وصف زيادة (لبن رايب، لبن بودرة...) بتفضل
  // تستخدم الجدول العادي تحت (containment match هيلاقي "لبن رايب" أطول
  // وأدق من الـ override ده لأنه بيتفحص الاسم المطبَّع بالظبط).
  { test: (n) => n === normalizeForLookup("لبن"), unit: "لتر" },
  // "قهوة بن وزن كيلو وهو يختار"
  {
    test: (n) => n.includes(normalizeForLookup("بن")) && (n.includes(normalizeForLookup("قهوه")) || n.includes(normalizeForLookup("قهوة"))),
    unit: "كيلو",
  },
];

// returns a default unit for a typed (already name-only, quantity/unit
// already stripped by parseQuantityLine) grocery line, or null if nothing
// matched well enough to guess confidently.
export function lookupDefaultUnit(rawName: string): string | null {
  const n = normalizeForLookup(rawName);
  if (!n) return null;

  for (const rule of OVERRIDE_RULES) {
    if (rule.test(n)) return rule.unit;
  }

  let best: { kw: string; unit: string } | null = null;
  for (const [kw, unit] of DEFAULT_UNIT_TABLE) {
    if (n === kw || n.includes(kw) || kw.includes(n)) {
      if (!best || kw.length > best.kw.length) best = { kw, unit };
    }
  }
  return best?.unit || null;
}
